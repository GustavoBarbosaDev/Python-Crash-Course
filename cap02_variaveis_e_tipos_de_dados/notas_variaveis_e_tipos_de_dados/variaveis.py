# Nomes de variáveis
# Ao usar variáveis é preciso seguir algumas regras e diretrizes. Quebrar algumas delas provocará erros
# 1. Nomes de variáveis podem contar apenas letras, números e underscores. Podem começar com uma letra ou underscore, mas não com número
# 2. Espaços não são permitidos em nomes de variáveis, mas underscores podem ser usados para separar palavras em nomes de variáveis
# 3. Evitar usar palavras reservadas e nomes de funções em Python como nomes de variáveis
# 4. Nomes de variáveis devem ser concisos, porém descritivos