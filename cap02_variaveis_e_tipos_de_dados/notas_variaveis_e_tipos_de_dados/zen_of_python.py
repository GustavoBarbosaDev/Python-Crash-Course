# A filosofia da comunidade Python está contida no "Zen de Python" de Tim Peters

# Bonito é melhor que feio
# Os programadores Python adotam a noção que o código pode ser bonito e elegante.
# Programadores sempre respeitaram soluções bem estruturadas, eficientes e até
# mesmo bonitas para os problemas

# Simples é melhor que complexo
# Se puder escolher entre uma solução simples e outra complexa, e as duas formas
# funcionarem, utilize a solução simples.
# Seu código será mais fácil de manter, e será mais simples para o programador 
# e outras pessoas desenvolverem com base no código posteriormente

# Complexo é melhor que complicado
# As vezes uma solução simples para um problema não é viável.
# Nesse caso, use a solução mais simples possível que funcione

# Legibilidade conta
# Mesmo que um código seja complexo, procure deixá-lo legível. 
# Sempre escreva comentários informativos para códigos complexos

# Deve haver uma e, de preferência, apenas uma maneira óbvia de fazer algo
# Boa parte da programação consiste em usar abordagens pequenas e comuns para 
# situações simples em um projeto maior e mais criativo.
# Os detalhes de funcionamento de um programa deve fazer sentido para outros
# programadores Python

# Agora é melhor que nunca
# Não tente escrever um código perfeito; escreva um código que funcione e, então,
# decida se deve aperfeiçoá-lo nesse projeto ou passar para algo novo.
