# Escrever códigos fáceis de ler ajuda a manter o controle sobre o que os programas fazem e também contribui para que
# outras pessoas entendam o código.
# Programadores profissionais seguem determinadas diretrizes e convenções para desenvolver bons hábitos.

# Guia de Estilo
# Um PEP (Python Enhancement Proposal) é um documento que propõe mudanças ou descreve padrões relacionados ao Python.
# A PEP 8 é o guia de estilo do Python e considera que o código é lido com mais frequência do que é escrito.
# O código pode ser escrito uma vez, mas será lido durante a manutenção, a depuração e a colaboração com outras pessoas.


# As seguintes diretrizes ajudam a escrever um código claro desde o início.

# Indentação
# A PEP 8 recomenda o uso de quatro espaços por nível de indentação. Isso melhora a legibilidade e deixa espaço para vários
# níveis de indentação em cada linha.
# Misturar tabulações com espaços em um arquivo pode causar problemas difíceis de diagnosticar.

# Tamanho da linha
# Recomenda-se que cada linha tenha no máximo 79 caracteres. A PEP 8 também recomenda limitar os comentários a 72 caracteres
# por linha.

# Linhas em branco
# Linhas em branco são usadas para agrupar partes do programa visualmente, mas não devem ser usadas de forma excessiva.
# Elas não afetam o modo como o código é executado, mas influenciam sua legibilidade.
# O interpretador Python utiliza a indentação horizontal para interpretar o significado do código, mas ignora o espaçamento
# vertical.